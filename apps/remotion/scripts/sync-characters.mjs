/**
 * Syncs the Lottie character catalog with the actual files on disk.
 *
 * Source of truth = the .json files in public/characters/lottie/. This script
 * reads them and (re)generates src/characters/lottie/catalog.generated.ts, from
 * which `LottieCharacterName` is derived automatically. So registering a new
 * Lottie creature is just: drop its .json here, then run `npm run sync:characters`.
 *
 * No manual type edits, ever. Run: npm run sync:characters
 */
import { readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const LOTTIE_DIR = resolve(__dirname, "../public/characters/lottie");
const OUT = resolve(__dirname, "../src/characters/lottie/catalog.generated.ts");

const names = readdirSync(LOTTIE_DIR)
  .filter((f) => f.toLowerCase().endsWith(".json"))
  .map((f) => f.replace(/\.json$/i, ""))
  .sort();

if (names.length === 0) {
  console.warn("No .json files found in", LOTTIE_DIR);
}

const list = names.map((n) => `  "${n}",`).join("\n");
const content = `// AUTO-GENERATED by scripts/sync-characters.mjs — do not edit by hand.
// Regenerate after adding/removing files in public/characters/lottie/:
//   npm run sync:characters

export const LOTTIE_CHARACTERS = [
${list}
] as const;

export type LottieCharacterName = (typeof LOTTIE_CHARACTERS)[number];
`;

writeFileSync(OUT, content);
console.log(`✓ Synced ${names.length} Lottie character(s) → src/characters/lottie/catalog.generated.ts`);
names.forEach((n) => console.log("   •", n));
